#!/usr/bin/env node
// Runs the full verification suite and writes TEST_RESULTS.md from real outputs:
// unit tests, every playtest (source build), single-file dist builds + their playtests.
// Usage: node tools/report.mjs [--skip-dist] [--only name]
import fs from 'node:fs';
import path from 'node:path';
import { execSync, spawnSync } from 'node:child_process';
import { playtest } from './playtest.mjs';
import { buildSingleHtml } from './lib/bundle.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
const lines = [];
const now = new Date().toISOString();
let env = {};
try { env = JSON.parse(fs.readFileSync(path.join(ROOT, 'capabilities.json'), 'utf8')); } catch { /* run doctor first for GPU info */ }

// 1. unit tests
const unit = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...fs.readdirSync(path.join(ROOT, 'tests/unit')).filter((f) => f.endsWith('.test.mjs')).map((f) => path.join(ROOT, 'tests/unit', f))], { encoding: 'utf8', cwd: ROOT });
const unitOut = unit.stdout;
const count = (k) => +(unitOut.match(new RegExp(`^# ${k} (\\d+)`, 'm'))?.[1] || 0);
const unitNames = [...unitOut.matchAll(/^(ok|not ok) \d+ - (.*)$/gm)].map((m) => [m[1] === 'ok', m[2]]);
console.log(`unit: ${count('pass')}/${count('tests')}`);

// 2. playtests
const projects = [...fs.readdirSync(path.join(ROOT, 'games')).map((g) => 'games/' + g), ...fs.readdirSync(path.join(ROOT, 'examples')).map((g) => 'examples/' + g)]
  .filter((d) => fs.existsSync(path.join(ROOT, d, 'playtest.json')) && (!only || d.includes(only)));
const rows = [];
for (const d of projects) {
  const dir = path.join(ROOT, d);
  console.log('playtest', d);
  const src = await playtest(dir, { log: () => {} });
  let dist = null;
  if (!args.includes('--skip-dist')) {
    const b = buildSingleHtml(dir, { root: ROOT });
    fs.mkdirSync(path.join(dir, 'dist'), { recursive: true });
    const file = path.join(dir, 'dist', path.basename(dir) + '.html'); fs.writeFileSync(file, b.html);
    dist = await playtest(dir, { file, resultsName: 'test-results.dist.json', shotsDir: path.join('/tmp', 'gf-dist-shots', path.basename(dir)), log: () => {} });
    dist.bytes = Buffer.byteLength(b.html);
  }
  rows.push({ d, src, dist });
  console.log(`  source ${src.summary}${dist ? ` | dist ${dist.summary}` : ''}`);
}

lines.push('# Test results', '', `Generated by \`node tools/report.mjs\` at ${now}. Every number below comes from an actual run in this environment; nothing is hand-edited.`, '');
lines.push('## Environment', '', `- Node ${process.version} on ${process.platform}`, `- Browser WebGL: ${env.gpu || 'see capabilities.json (run `gameforge doctor`)'}`, `- Software rendering: ${env.software ? '**yes (SwiftShader)** — fps figures are not representative of real GPUs; tests verify behaviour, not speed' : 'unknown/no'}`, '');
lines.push('## Unit tests (`npm test`)', '', `**${count('pass')}/${count('tests')} passed**, ${count('fail')} failed.`, '', ...unitNames.map(([ok, n]) => `- ${ok ? '✅' : '❌'} ${n}`), '');
lines.push('## Automated gameplay playtests', '', 'Each project is driven through `window.__GF` in headless Chromium with deterministic fixed-step simulation (see `skills/gameforge/references/testing.md`). "Dist" is the single-file HTML build loaded from `file://`.', '');
lines.push('| Project | Source build | Dist single-file | Dist size | Draw calls | Triangles | Load (ms) |', '|---|---|---|---|---|---|---|');
for (const r of rows) lines.push(`| \`${r.d}\` | ${r.src.passed ? '✅' : '❌'} ${r.src.summary} | ${r.dist ? `${r.dist.passed ? '✅' : '❌'} ${r.dist.summary}` : 'skipped'} | ${r.dist ? (r.dist.bytes / 1e6).toFixed(2) + ' MB' : '-'} | ${r.src.metrics?.calls ?? '-'} | ${r.src.metrics?.triangles?.toLocaleString?.() ?? '-'} | ${r.src.loadMs ?? '-'} |`);
lines.push('');
for (const r of rows) {
  lines.push(`### ${r.d}`, '', ...r.src.checks.map((c) => `- ${c.ok ? '✅' : '❌'} ${c.label}${c.detail !== undefined ? ` — \`${typeof c.detail === 'string' ? c.detail : JSON.stringify(c.detail)}\`` : ''}`), '');
  if (r.src.screenshots.length) lines.push('Screenshots: ' + r.src.screenshots.map((s) => `[${path.basename(s)}](${r.d}/${s})`).join(' · '), '');
}
lines.push('## How to reproduce', '', '```bash', 'node tools/gameforge.mjs doctor   # environment capabilities', 'npm test                          # unit tests', 'node tools/report.mjs             # all playtests + dist builds -> TEST_RESULTS.md', '```', '');
fs.writeFileSync(path.join(ROOT, 'TEST_RESULTS.md'), lines.join('\n'));
const allOk = unit.status === 0 && rows.every((r) => r.src.passed && (!r.dist || r.dist.passed));
console.log(allOk ? 'ALL PASSED' : 'FAILURES PRESENT');
process.exit(allOk ? 0 : 1);
