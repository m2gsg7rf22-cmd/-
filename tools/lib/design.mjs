// Game Design Document + task graph generation from a GameForge spec.
// The GDD is a design artifact, never evidence of an implemented game.

const GENRE_LOOPS = {
  action: 'Explore → encounter enemies → fight with combos, dodges and blocks → earn XP/loot → face a tougher wave or boss.',
  driving: 'Drive → hit checkpoints / objectives → avoid traffic and obstacles → beat the clock → improve best time.',
  adventure: 'Explore → talk to characters → accept quests → find items/locations → unlock story beats → reach the ending.',
  exploration: 'Wander a handcrafted-procedural world → discover landmarks and collectibles → piece together lore.',
  survival: 'Survive waves or a timer → gather pickups → manage health and stamina → outlast the threat.',
  racing: 'Race through gates → drift and boost for time → finish → retry for a better time.',
  collectathon: 'Traverse the world → find every collectible → unlock the finale.',
};

export function generateGDD(spec) {
  const g = spec.genre || (spec.player?.mode === 'vehicle' ? 'driving' : spec.enemies?.length ? 'action' : spec.npcs?.length ? 'adventure' : 'exploration');
  const w = spec.world || {};
  const list = (a, f) => (a && a.length ? a.map(f).join('\n') : '- _None specified — Game Designer to decide._');
  return `# ${spec.title} — Game Design Document

> Generated by GameForge from \`game.spec.js\`. This document describes the intended game; it is **not** evidence that anything is implemented. Implementation status is tracked in \`tasks.json\` and verified by \`playtest.json\`.

## 1. Overview
- **Pitch:** ${spec.pitch || spec.description || 'TBD'}
- **Genre:** ${g}
- **Target platform:** desktop browsers (WebGL2), touch fallback controls on mobile
- **Session length:** ${spec.sessionLength || '10–30 minutes'}
- **References (quality targets only, no copied assets):** ${(spec.references || []).join(', ') || 'n/a'}

## 2. Core gameplay loop
${spec.coreLoop || GENRE_LOOPS[g] || GENRE_LOOPS.exploration}

## 3. World and level structure
- **World type:** ${w.type || 'hills'} · **Biome:** ${w.biome || 'temperate'} · **Size:** ${w.size || 360} m · **Time of day:** ${w.timeOfDay ?? 'biome default'}${w.dayLength ? ` · day/night cycle ${w.dayLength}s` : ''}
- **Landmarks:**
${list(spec.landmarks, (l) => `  - ${l.id || l.kind} (${l.kind}) at ${l.at || `${l.x},${l.z}`}`)}

## 4. Story, characters and missions
- **Premise:** ${spec.story?.premise || spec.pitch || 'TBD'}
- **Characters:**
${list(spec.story?.characters || spec.npcs, (n) => `  - **${n.name}** (${n.id}) — ${n.role || 'NPC'}${n.want ? `; wants: ${n.want}` : ''}${n.dialogue ? ', has dialogue' : ''}`)}
- **Quests / missions:**
${spec.story ? `  - Story script: ${spec.story.title || spec.story.id} — review with \`gameforge story <file.story.js>\` (graph + story bible)\n` : ''}${list(spec.quests?.length ? spec.quests : (spec.story?.missions || (spec.story?.acts || []).flatMap((a) => (a.missions || []).filter((m) => typeof m === 'object'))), (q) => `  - **${q.title}** — ${q.description || q.summary || ''} Objectives: ${(q.objectives || []).map((o) => o.text).join('; ')}`)}

## 5. Art direction
- **Style:** ${spec.art?.style || 'stylized-realistic PBR, readable silhouettes, procedural textures'}
- **Palette:** biome "${w.biome || 'temperate'}"${spec.theme ? `, UI accent ${spec.theme.accent}` : ''}
- **Hero assets:** ${(spec.art?.heroAssets || []).join(', ') || 'player character, signature landmark'}
- **Lighting:** physically based sky, sun shadows, image-based lighting, ${w.timeOfDay !== undefined ? `time ${w.timeOfDay}h` : 'biome default time'}

## 6. Controls and camera
- **Player mode:** ${spec.player?.mode || 'onfoot'}${spec.player?.combat ? ' with melee combat' : ''}
- **Camera:** ${spec.player?.mode === 'vehicle' ? 'chase camera with speed FOV' : 'third-person orbit with collision, lock-on'}
- **Input:** keyboard + mouse, gamepad (standard mapping), touch joystick; all actions remappable in Settings

## 7. Mechanics and progression
- **Goal:** ${spec.goal?.type || 'explore'}${spec.goal?.label ? ` — ${spec.goal.label}` : ''}
- **Enemies:**
${list(spec.enemies, (e) => `  - ${e.count ?? 1}× ${e.type}${e.boss ? ' (boss)' : ''}${e.at ? ` near ${e.at}` : ''}`)}
- **Collectibles:**
${list(spec.collectibles, (c) => `  - ${c.count ?? 5}× ${c.item || c.kind}`)}
- **Progression:** XP from enemies and quests → levels (health/damage scaling)

## 8. Technical architecture
- GameForge engine (vendored three.js r180 renderer, in-house physics/AI/audio/UI), no install, no build step for development
- Modules: \`src/world.js\`, \`src/assets.js\`, \`src/story.js\`, \`src/gameplay.js\`, \`src/ai.js\`, \`src/audio.js\`, \`src/hud.js\`, \`src/animation.js\`, \`src/graphics.js\`; composed by \`main.js\` via \`composeGame(SPEC)\`
- Deterministic fixed-step loop (60 Hz) with \`window.__GF\` test hooks

## 9. Asset requirements
All assets are generated procedurally at load time (no files, no paid generators): terrain, vegetation, buildings, props, characters, animation clips, textures, SFX and music.
${(spec.assets || []).map((a) => `- ${a}`).join('\n')}

## 10. Performance targets
- 60 fps on a mid-range discrete/integrated GPU at 1080p on the "medium" tier; quality tiers auto-detected (low/medium/high)
- Draw calls < 300, triangles < 1.5M on high; shadow map ≤ 4096
- Note: headless CI uses software WebGL (SwiftShader) and is expected to run far below these targets; it verifies correctness, not speed

## 11. Completion criteria
- [ ] \`node tools/playtest.mjs .\` passes every check in \`playtest.json\`
- [ ] No runtime errors in the console
- [ ] Title → play → win/lose → retry flow works
- [ ] \`node tools/gameforge.mjs build .\` produces \`dist/${spec.id || 'game'}.html\` that also passes the playtest via file://
- [ ] Screenshots reviewed against the art direction
${(spec.acceptance || []).map((a) => `- [ ] ${a}`).join('\n')}
`;
}

// Specialist roles used by the task graph (mirrors .claude/agents/*.md).
export const ROLES = ['game-director', 'game-designer', 'narrative-director', '3d-artist', 'material-artist', 'world-builder', 'character-director', 'animation-director', 'gameplay-engineer', 'graphics-engineer', 'physics-engineer', 'ai-engineer', 'audio-director', 'ui-ux-designer', 'qa-engineer', 'performance-engineer', 'integration-engineer'];

export function generateTasks(spec) {
  const hasStory = (spec.npcs?.length || 0) + (spec.quests?.length || 0) > 0 || !!spec.story;
  const hasEnemies = (spec.enemies?.length || 0) > 0;
  const vehicle = spec.player?.mode === 'vehicle' || spec.world?.type === 'city';
  const T = [];
  const add = (id, role, title, { deps = [], owns = [], accept = [], wave }) => T.push({ id, role, title, deps, owns, acceptance: accept, wave, status: 'pending' });
  add('design', 'game-designer', 'Finalize game.spec.js: goal, mechanics, enemies, collectibles, tuning numbers', { owns: ['game.spec.js', 'GDD.md'], accept: ['GDD.md regenerated (gameforge gdd)', 'spec passes gameforge validate'], wave: 0 });
  add('architecture', 'game-director', 'Confirm module boundaries and write ARCHITECTURE notes in README.md', { deps: ['design'], owns: ['README.md', 'tasks.json'], accept: ['every task has an owner and acceptance criteria'], wave: 1 });
  add('world', 'world-builder', 'Terrain/city, landmarks, spawn points and level layout', { deps: ['architecture'], owns: ['src/world.js'], accept: ['player spawns grounded', 'landmarks reachable (no walls blocking)'], wave: 2 });
  add('assets', '3d-artist', 'Hero props and signature landmark meshes', { deps: ['architecture'], owns: ['src/assets.js'], accept: ['gameforge validate reports no invalid geometry', 'screenshot shows hero assets'], wave: 2 });
  add('graphics', 'graphics-engineer', 'Lighting, sky, post-processing and quality tiers', { deps: ['architecture'], owns: ['src/graphics.js'], accept: ['canvas check passes', 'no blown-out or black frames in screenshots'], wave: 2 });
  add('animation', 'animation-director', 'Custom animation clips and animation event hooks', { deps: ['architecture'], owns: ['src/animation.js'], accept: ['new clips play without errors'], wave: 2 });
  if (hasStory) add('story', 'narrative-director', 'Story script (story/*.story.js), branching dialogue, quest chain, cutscenes', { deps: ['architecture'], owns: ['src/story.js', 'story/'], accept: ['gameforge story: no FAIL (every dialogue node reachable, every branch playable to the ending)', 'quest chain completes in playtest'], wave: 2 });
  if (hasEnemies) add('ai', 'ai-engineer', 'Enemy archetypes, behaviour trees, encounter pacing', { deps: ['architecture'], owns: ['src/ai.js'], accept: ['enemies perceive, pursue and attack in playtest', 'enemies can be defeated'], wave: 2 });
  add('audio', 'audio-director', 'Music moods per state, SFX hooks, ambience', { deps: ['architecture'], owns: ['src/audio.js'], accept: ['audioEvents > 0 in playtest metrics'], wave: 2 });
  add('hud', 'ui-ux-designer', 'HUD widgets, menus, accessibility options', { deps: ['architecture'], owns: ['src/hud.js'], accept: ['menu → play → pause → resume works', 'text scale and subtitles settings work'], wave: 2 });
  add('gameplay', 'gameplay-engineer', 'Core rules, win/lose, progression, interactions', { deps: ['world', ...(hasEnemies ? ['ai'] : []), ...(hasStory ? ['story'] : [])], owns: ['src/gameplay.js'], accept: ['goal can be completed', 'game over and victory screens reachable'], wave: 3 });
  if (vehicle) add('physics', 'physics-engineer', 'Vehicle tuning, collisions, dynamic props', { deps: ['world'], owns: ['src/physics.js'], accept: ['car accelerates, steers, brakes', 'cannot drive through buildings'], wave: 3 });
  add('integration', 'integration-engineer', 'Wire modules in main.js, resolve conflicts, build dist', { deps: T.filter((t) => t.wave >= 2).map((t) => t.id), owns: ['main.js', 'index.html'], accept: ['game boots with no console errors', 'gameforge build succeeds'], wave: 4 });
  add('qa', 'qa-engineer', 'Extend playtest.json to cover every mechanic; run and file bugs', { deps: ['integration'], owns: ['playtest.json', 'test-results.json'], accept: ['all playtest checks pass on source and dist builds'], wave: 5 });
  add('performance', 'performance-engineer', 'Profile metrics, reduce draw calls/triangles, tune quality tiers', { deps: ['integration'], owns: ['PERF.md'], accept: ['metrics recorded', 'no tier exceeds budgets in GDD §10'], wave: 5 });
  add('polish', 'game-director', 'Review screenshots vs art direction, assign fixes, final sign-off', { deps: ['qa', 'performance'], owns: [], accept: ['all tasks done', 'limitations documented'], wave: 6 });
  return { spec: spec.id, generated: new Date().toISOString(), waves: Math.max(...T.map((t) => t.wave)) + 1, tasks: T };
}

// Validate a task graph: unknown deps, cycles, and parallel write conflicts.
export function validateTasks(graph) {
  const errors = [], ids = new Set(graph.tasks.map((t) => t.id));
  for (const t of graph.tasks) for (const d of t.deps) if (!ids.has(d)) errors.push(`${t.id}: unknown dependency ${d}`);
  const byWave = {};
  for (const t of graph.tasks) (byWave[t.wave] ||= []).push(t);
  for (const [w, list] of Object.entries(byWave)) {
    const owner = {};
    for (const t of list) for (const f of t.owns) { if (owner[f]) errors.push(`wave ${w}: ${t.id} and ${owner[f]} both write ${f}`); owner[f] = t.id; }
  }
  const map = Object.fromEntries(graph.tasks.map((t) => [t.id, t]));
  for (const t of graph.tasks) for (const d of t.deps) if (map[d] && map[d].wave >= t.wave) errors.push(`${t.id} (wave ${t.wave}) depends on ${d} (wave ${map[d].wave}) which is not earlier`);
  const seen = new Set(), stack = new Set();
  const visit = (id) => { if (stack.has(id)) { errors.push('cycle at ' + id); return; } if (seen.has(id)) return; stack.add(id); for (const d of map[id]?.deps || []) visit(d); stack.delete(id); seen.add(id); };
  for (const t of graph.tasks) visit(t.id);
  return { ok: errors.length === 0, errors };
}

// Generate a baseline playtest scenario covering the spec's mechanics.
export function generatePlaytest(spec) {
  const steps = [
    { do: 'step', frames: 30 },
    { do: 'expect', path: 'state', op: '==', value: 'menu', label: 'title menu on boot' },
    { do: 'screenshot', name: '01-title' },
    { do: 'call', fn: 'startGame' }, { do: 'step', frames: 60 },
    { do: 'expect', path: 'state', op: '==', value: 'playing', label: 'game starts' },
    { do: 'canvas', label: 'gameplay frame renders' },
    { do: 'screenshot', name: '02-gameplay' },
  ];
  if (spec.player?.mode === 'vehicle') {
    steps.push({ do: 'hold', action: 'accelerate' }, { do: 'step', frames: 120 }, { do: 'release', action: 'accelerate' },
      { do: 'expect', path: 'vehicle.kmh', op: '>', value: 20, label: 'vehicle accelerates' });
  } else {
    steps.push({ do: 'expect', path: 'player.grounded', op: 'truthy', label: 'player is grounded' },
      { do: 'hold', action: 'moveForward' }, { do: 'step', frames: 40 }, { do: 'release', action: 'moveForward' },
      { do: 'press', action: 'jump' }, { do: 'step', frames: 6 }, { do: 'expect', path: 'player.grounded', op: 'falsy', label: 'jump works' }, { do: 'step', frames: 60 });
  }
  if (spec.enemies?.length) {
    steps.push({ do: 'eval', js: 'window.__GF.cheat.god()' }, { do: 'step', frames: 30 },
      { do: 'expect', path: 'enemiesAlive', op: '>', value: 0, label: 'enemies spawned' },
      { do: 'eval', js: 'window.__GF.cheat.killAll()' }, { do: 'step', frames: 30 },
      { do: 'expect', path: 'enemiesAlive', op: '==', value: 0, label: 'enemies can be defeated' });
  }
  for (const n of spec.npcs || []) if (n.dialogue) {
    steps.push({ do: 'eval', js: `window.__GF.cheat.goTo('npc:${n.id}')` }, { do: 'step', frames: 6 },
      { do: 'expect', path: 'focus', op: '==', value: `npc:${n.id}`, label: `can approach ${n.name}` },
      { do: 'press', action: 'interact' }, { do: 'step', frames: 20 },
      { do: 'expect', path: 'state', op: '==', value: 'dialogue', label: `talking to ${n.name} opens dialogue` },
      { do: 'eval', js: "for (let i = 0; i < 12 && window.__GF.state().state === 'dialogue'; i++) { window.__GF.press('interact'); window.__GF.press('choice1'); window.__GF.step(150); }" },
      { do: 'expect', path: 'state', op: '!=', value: 'dialogue', label: `conversation with ${n.name} ends` });
    break;
  }
  if (spec.collectibles?.length && spec.player?.mode !== 'vehicle') {
    steps.push({ do: 'eval', js: "window.__GF.cheat.goTo(window.__GF.game.collectibles.find(c => !c.taken).id)" }, { do: 'step', frames: 6 },
      { do: 'press', action: 'interact' }, { do: 'step', frames: 20 },
      { do: 'expect', path: 'collected', op: '>=', value: 1, label: 'collectible can be picked up' });
  }
  if (spec.goal?.type === 'collect') steps.push({ do: 'eval', js: 'window.__GF.cheat.collectAll()' }, { do: 'step', frames: 120 }, { do: 'expect', path: 'state', op: '==', value: 'gameover', label: 'collecting everything wins the game' });
  if (spec.goal?.type === 'defeat') steps.push({ do: 'step', frames: 120 }, { do: 'expect', path: 'state', op: '==', value: 'gameover', label: 'defeating all enemies wins the game' });
  steps.push({ do: 'screenshot', name: '03-end' });
  return { name: spec.title, quality: 'low', steps };
}
