# Regenerates examples/recipes-lab/src/*.js from skills/gameforge/references/recipes.md so the
# documented recipes are executed verbatim by the lab playtest. Usage: python3 tools/lib/recipes-lab.py
import re, os
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(root, 'skills/gameforge/references/recipes.md')).read()
blocks = re.findall(r'^## ([^\n]*)\n```js\n(.*?)```', src, re.S | re.M)
mods = {}
for title, code in blocks:
    m = re.search(r'\((\w+)\.js', title)
    if m: mods.setdefault(m.group(1), []).append((title, code))
for mod, items in mods.items():
    body = "\n".join(f"  // ---- recipe: {t}\n  {{\n" + "\n".join('    ' + l for l in c.strip().splitlines()) + "\n  }" for t, c in items)
    open(os.path.join(root, f'examples/recipes-lab/src/{mod}.js'), 'w').write(
        "// Generated by tools/lib/recipes-lab.py from references/recipes.md (recipes run verbatim).\n"
        "import * as GF from '../../../engine/index.js';\n\nexport function install(game) {\n"
        "  const { app, player } = game; const { THREE } = GF;\n" + body + "\n}\n")
    print(mod, len(items))
